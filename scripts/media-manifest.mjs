// Builds scripts/media-manifest.json: the exact list of files the site can request from its media folders, with size,
// SHA-256 and content type. scripts/upload-media.mjs uploads exactly this list to the Supabase bucket and checks it.
// Nothing is deleted or moved. Files in the media folders that no page asks for are listed but not uploaded.
//   node scripts/media-manifest.mjs            writes scripts/media-manifest.json and prints a summary
//   node scripts/media-manifest.mjs --check    exits 1 if the committed manifest is out of date (also run by npm test)
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { CONTENT_TYPES, classifyMedia } from "./lib/media-refs.mjs";

export const BUCKET = "website-media";
const here = path.dirname(fileURLToPath(import.meta.url));
export const defaultRoot = path.resolve(here, "..");
export const manifestPath = path.join(here, "media-manifest.json");

/** Names the code uses on purpose although no file exists in git. Anything else that is named but missing is an error. */
export const KNOWN_ABSENT = {
  "/media/hero-loop.mp4": "heroVideo.file in lib/content/media.ts; no component uses it and .vercelignore keeps public/media/*.mp4 out of deployments",
};

const sha256 = (file) => createHash("sha256").update(readFileSync(file)).digest("hex");

/** Names that point at a git-ignored PNG/JPEG master are fine while the shipped WebP twin exists. */
function unexpectedAbsent(absent, existing) {
  return absent.filter((p) => {
    if (KNOWN_ABSENT[p]) return false;
    const twin = p.replace(/^(\/media\/[^/]+)\.(png|jpe?g)$/i, "$1.webp");
    return !(twin !== p && existing.has(twin));
  });
}

export function buildManifest(root = defaultRoot) {
  const { served, unserved, absent, namedButNotUploadable } = classifyMedia(root);
  const existing = new Set([...served, ...unserved].map((f) => f.web));
  const files = served.map((f) => ({ path: f.web.slice(1), bytes: f.bytes, sha256: sha256(f.full), type: CONTENT_TYPES[f.ext] }));
  const manifest = {
    bucket: BUCKET,
    comment: "Generated by scripts/media-manifest.mjs. Do not edit by hand; run it again after changing media or the code that names it.",
    count: files.length,
    totalBytes: files.reduce((sum, f) => sum + f.bytes, 0),
    files,
  };
  return { manifest, unserved, unexpectedAbsent: unexpectedAbsent(absent, existing), namedButNotUploadable };
}

const mb = (bytes) => `${(bytes / 1048576).toFixed(1)} MB`;

async function main() {
  const check = process.argv.includes("--check");
  const { manifest, unserved, unexpectedAbsent: missing, namedButNotUploadable: odd } = buildManifest();
  const text = `${JSON.stringify(manifest, null, 2)}\n`;
  console.log(`Served by the site: ${manifest.count} files, ${mb(manifest.totalBytes)} (these are uploaded).`);
  console.log(`In the media folders but never requested: ${unserved.length} files, ${mb(unserved.reduce((s, f) => s + f.bytes, 0))} (not uploaded, not deleted).`);
  if (missing.length) {
    console.error(`The code names ${missing.length} file(s) that do not exist in public/:\n  ${missing.join("\n  ")}`);
    process.exit(1);
  }
  if (odd.length) {
    console.error(`The code names ${odd.length} file(s) of a type the media bucket does not serve:\n  ${odd.join("\n  ")}`);
    process.exit(1);
  }
  if (check) {
    let current = "";
    try { current = readFileSync(manifestPath, "utf8"); } catch {}
    if (current !== text) {
      console.error("scripts/media-manifest.json is out of date. Run: node scripts/media-manifest.mjs");
      process.exit(1);
    }
    console.log("scripts/media-manifest.json is up to date.");
    return;
  }
  writeFileSync(manifestPath, text);
  console.log(`Wrote ${path.relative(process.cwd(), manifestPath)}`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) await main();
