import assert from 'node:assert/strict';
import { createHash, createHmac, randomBytes } from 'node:crypto';
import { readFileSync } from 'node:fs';
import ts from 'typescript';

const source = readFileSync(new URL('../lib/security/trustee.ts', import.meta.url), 'utf8');
const { outputText } = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } });
const security = await import(`data:text/javascript;base64,${Buffer.from(outputText).toString('base64')}`);
const secret = randomBytes(48).toString('hex');
const code = randomBytes(24).toString('hex');
const invite = { id: 'test-school', institution: 'Test Institution', codeHash: createHash('sha256').update(code).digest('hex'), expiresAt: new Date(Date.now() + 86400000).toISOString() };
process.env.TRUSTEE_SESSION_SECRET = secret;
process.env.TRUSTEE_INVITATIONS_JSON = JSON.stringify([invite]);
assert.equal(security.matchInvitation('wrong-code'), null);
assert.equal(security.matchInvitation(code).id, invite.id);
const token = security.createTrusteeSession(invite);
assert.equal(security.readTrusteeSession(token).institution, invite.institution);
assert.equal(security.readTrusteeSession(token + 'x'), null);
assert.equal(security.readTrusteeSession('malformed'), null);
const expired = Buffer.from(JSON.stringify({ id: invite.id, exp: Date.now() - 1000 })).toString('base64url');
assert.equal(security.readTrusteeSession(`${expired}.${createHmac('sha256', secret).update(expired).digest('base64url')}`), null);
process.env.TRUSTEE_INVITATIONS_JSON = '[]';
assert.equal(security.readTrusteeSession(token), null);
process.env.TRUSTEE_INVITATIONS_JSON = JSON.stringify([{ ...invite, expiresAt: '2000-01-01T00:00:00Z' }]);
assert.equal(security.matchInvitation(code), null);
assert.equal(security.readTrusteeSession(token), null);
process.env.TRUSTEE_SESSION_SECRET = '';
assert.equal(security.trusteeConfig(), null);
console.log('PASS: correct/wrong codes, signed sessions, tampering, expiry, invitation revocation and fail-closed configuration.');
